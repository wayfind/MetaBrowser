#!/usr/bin/env python3
"""One reviewed tool catalogue for AgentCore registration and external MCP."""
import argparse, json, pathlib

root = pathlib.Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
definitions = json.loads((root / 'src/browser_tool_catalog.json').read_text())
assert len({d['name'] for d in definitions}) == len(definitions)
quote = lambda value: json.dumps(value, ensure_ascii=False)
zig = '// Generated by scripts/generate-browser-catalog.py. Do not edit.\n'
for field, key in [('names', 'name'), ('descriptions', 'description')]:
    zig += 'pub const ' + field + ' = [_][:0]const u8{\n'
    zig += ''.join('    ' + quote(d[key]) + ',\n' for d in definitions) + '};\n'
zig += 'pub const schemas = [_][:0]const u8{\n'
zig += ''.join('    ' + quote(json.dumps(d['inputSchema'], separators=(',', ':'))) + ',\n' for d in definitions) + '};\n'
zig += 'pub const read_names = [_][]const u8{\n'
zig += ''.join('    ' + quote(d['name']) + ',\n' for d in definitions if d['readOnly']) + '};\n'
catalogue = []
for d in definitions:
    item = {k: d[k] for k in ['name', 'description', 'inputSchema']}
    item['annotations'] = {'readOnlyHint': d['readOnly'], 'destructiveHint': not d['readOnly'], 'openWorldHint': True}
    catalogue.append(item)
cpp = '// Generated by scripts/generate-browser-catalog.py. Do not edit.\n'
cpp += 'constexpr char kBrowserToolCatalog[] = R"MBTOOLS(' + json.dumps(catalogue, ensure_ascii=False, separators=(',', ':')) + ')MBTOOLS";\n'
for path, text in [(root / 'src/browser_catalog.zig', zig), (root / 'chromium/metabrowser/browser_tool_catalog.inc', cpp)]:
    if args.check:
        assert path.read_text() == text, 'Stale generated catalogue: ' + str(path)
    else:
        path.write_text(text)
